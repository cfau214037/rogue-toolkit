local name, ns = ...
ns.icon = "Interface\\AddOns\\" .. name .. "\\Textures\\Logo"

function ns.launcher(title, db, open, menu)
    local b = CreateFrame("Button", nil, Minimap)
    b:SetSize(32, 32)
    b:SetFrameLevel(Minimap:GetFrameLevel() + 8)
    b:RegisterForClicks("LeftButtonUp", "RightButtonUp")
    b:RegisterForDrag("LeftButton")
    local icon = b:CreateTexture(nil, "ARTWORK")
    icon:SetSize(23, 23)
    icon:SetPoint("CENTER")
    icon:SetTexture(ns.icon)
    local ring = b:CreateTexture(nil, "OVERLAY")
    ring:SetSize(53, 53)
    ring:SetPoint("TOPLEFT", b, "CENTER", -17, 15)
    ring:SetTexture(136430)
    b:SetHighlightTexture("Interface\\Minimap\\UI-Minimap-ZoomButton-Highlight")
    local function position()
        local a = math.rad(db.angle or 145)
        b:SetPoint("CENTER", Minimap, "CENTER", math.cos(a)*(Minimap:GetWidth()/2+5), math.sin(a)*(Minimap:GetHeight()/2+5))
    end
    position()
    b:SetScript("OnDragStart", function()
        GameTooltip:Hide()
        b:SetScript("OnUpdate", function()
            local x,y = GetCursorPosition()
            local cx,cy = Minimap:GetCenter()
            local scale = Minimap:GetEffectiveScale()
            db.angle = math.deg(math.atan2(y/scale-cy, x/scale-cx))
            position()
        end)
    end)
    b:SetScript("OnDragStop", function() b:SetScript("OnUpdate", nil) end)
    b:SetScript("OnHide", function() b:SetScript("OnUpdate", nil) end)
    b:SetScript("OnClick", function(self, mouse)
        GameTooltip:Hide()
        if mouse == "RightButton" then menu(self) else open() end
    end)
    b:SetScript("OnEnter", function(self)
        GameTooltip:SetOwner(self, "ANCHOR_LEFT")
        GameTooltip:AddLine(title)
        GameTooltip:AddLine("Left-click to open. Right-click for options.", 1, 1, 1)
        GameTooltip:AddLine("Drag to move.", 0.8, 0.8, 0.8)
        GameTooltip:Show()
    end)
    b:SetScript("OnLeave", GameTooltip_Hide)
    return b
end
